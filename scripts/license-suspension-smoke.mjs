const base=process.env.HML_SMOKE_BASE_URL||'http://127.0.0.1:8788';
const username=process.env.HML_SMOKE_USERNAME||'homologacao';
const password=process.env.HML_SMOKE_PASSWORD||'ci-hml-secret';
const authorization=`Basic ${Buffer.from(`${username}:${password}`).toString('base64')}`;
const same={'content-type':'application/json',origin:base,authorization};
const assert=(c,m)=>{if(!c)throw new Error(m)};
const req=async(path,opt={})=>{const r=await fetch(`${base}${path}`,{...opt,redirect:opt.redirect||'manual',headers:{authorization,...(opt.headers||{})}});const p=await r.json().catch(()=>({}));return{r,p}};
console.log('HML suspended license smoke testing');
const state=await req('/api/license/status');
assert(state.r.ok,`license status returned ${state.r.status}`);
assert(state.p.data?.status==='suspended',`expected suspended, got ${state.p.data?.status}`);
assert(state.p.data?.access==='blocked',`expected blocked access, got ${state.p.data?.access}`);
const app=await req('/app');
assert(app.r.status===302,`suspended /app should redirect, got ${app.r.status}`);
assert((app.r.headers.get('location')||'').includes('/license.html'),'suspended /app did not redirect to license screen');
const mutation=await req('/api/catalog',{method:'POST',headers:same,body:JSON.stringify({name:'Bloqueado CI',price_cents:100})});
assert(mutation.r.status===402,`suspended catalog mutation should be 402, got ${mutation.r.status}`);
assert(mutation.p.code==='license_suspended','suspended mutation missing license_suspended code');
const company=await req('/api/company-settings');
assert(company.r.ok,`company settings should remain readable while suspended, got ${company.r.status}`);
const billing=await req('/api/billing/pix',{method:'POST',headers:same,body:'{}'});
assert(billing.r.status===503,`billing provider should remain reachable and report 503 in CI, got ${billing.r.status}`);
assert(billing.p.code==='provider_not_configured','billing route was blocked by license gate');
console.log('HML suspended license smoke test passed.');
