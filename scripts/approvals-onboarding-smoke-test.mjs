const base=process.env.HML_SMOKE_BASE_URL||'http://127.0.0.1:8788';
const auth=`Basic ${Buffer.from(`${process.env.HML_SMOKE_USERNAME||'homologacao'}:${process.env.HML_SMOKE_PASSWORD||'ci-hml-secret'}`).toString('base64')}`;
const headers={authorization:auth,'content-type':'application/json',origin:base};
const req=async(path,opt={})=>{const r=await fetch(base+path,{...opt,headers:{...headers,...(opt.headers||{})}});const p=await r.json().catch(()=>({}));if(!r.ok)throw new Error(`${path}: ${r.status} ${p.error||''}`);return p.data};
const assert=(x,m)=>{if(!x)throw new Error(m)};
console.log('Approvals/onboarding smoke testing',base);
const onboarding=await req('/api/onboarding/progress',{headers:{authorization:auth}});
assert(onboarding&&onboarding.total_steps===6,'onboarding total steps invalid');
assert(Number.isFinite(Number(onboarding.completed_steps)),'onboarding completed steps missing');
assert(typeof onboarding.current_step==='string','onboarding current step missing');
const created=await req('/api/assistant/actions',{method:'POST',body:JSON.stringify({action_type:'send_collection_message',entity_type:'receivable',entity_id:'recv-smoke',title:'Cobrança de homologação',description:'Proposta de cobrança criada apenas para teste.',risk_level:'high',payload:{channel:'whatsapp',message:'Mensagem de homologação. Não enviar.'},expires_hours:2})});
assert(created.status==='pending','new action must be pending');
assert(created.action_type==='send_collection_message','action type mismatch');
const pending=await req('/api/assistant/actions?status=pending',{headers:{authorization:auth}});
assert(Array.isArray(pending),'pending actions list missing');
assert(pending.some(x=>x.id===created.id&&x.status==='pending'),'created action not found in pending queue');
const reviewed=await req(`/api/assistant/actions/${encodeURIComponent(created.id)}/review`,{method:'POST',body:JSON.stringify({decision:'approve'})});
assert(reviewed.status==='approved','approval did not persist');
const approved=await req('/api/assistant/actions?status=approved',{headers:{authorization:auth}});
const row=approved.find(x=>x.id===created.id);
assert(row&&row.status==='approved','approved action not found');
assert(!row.executed_at,'approved action must not execute automatically');
let conflict=false;
try{await req(`/api/assistant/actions/${encodeURIComponent(created.id)}/review`,{method:'POST',body:JSON.stringify({decision:'reject'})})}catch(e){conflict=String(e.message).includes('409')}
assert(conflict,'second review must be rejected with conflict');
console.log('Approvals and live onboarding smoke test passed.');
